const RECENT_KEY = 'note-emoji-recent'
const RECENT_MAX = 24

export function loadRecentEmojis(): string[] {
  try {
    const value = uni.getStorageSync(RECENT_KEY)
    return Array.isArray(value) ? value.filter((item): item is string => typeof item === 'string' && item.trim() !== '') : []
  } catch {
    return []
  }
}

export function pushRecentEmoji(emoji: string): string[] {
  const next = [emoji, ...loadRecentEmojis().filter((item) => item !== emoji)].slice(0, RECENT_MAX)
  try {
    uni.setStorageSync(RECENT_KEY, next)
  } catch {
    // 存储不可用时仅影响最近使用，不影响插入。
  }
  return next
}