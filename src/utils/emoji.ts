export interface EmojiCategory {
  id: string
  name: string
  emojis: string[]
}

type EmojiSpec = number | [number, number]

// 码位默认文本呈现的符号需追加 VS16，保证移动端按彩色表情渲染。
const VARIATION_SELECTOR_16 = new Set([
  0x2764, 0x270c, 0x270d, 0x2615, 0x2600, 0x2601, 0x2602, 0x2744, 0x26a1,
  0x2b50, 0x26f2, 0x26f3, 0x26f5, 0x26be, 0x26bd, 0x2328, 0x231b, 0x267b,
  0x1f3ce, 0x1f5a5, 0x1f5a8, 0x1f399, 0x1f6e0, 0x1f6cf, 0x1f6cb
])

function build(specs: EmojiSpec[]): string[] {
  const emojis: string[] = []
  for (const spec of specs) {
    const [from, to] = Array.isArray(spec) ? spec : [spec, spec]
    for (let code = from; code <= to; code++) {
      emojis.push(String.fromCodePoint(code) + (VARIATION_SELECTOR_16.has(code) ? '\ufe0f' : ''))
    }
  }
  return emojis
}

