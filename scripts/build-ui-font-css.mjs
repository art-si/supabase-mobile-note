import { readFile, readdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import subsetFont from 'subset-font'

const root = resolve(import.meta.dirname, '..')
const fontPath = resolve(root, 'src/assets/fonts/note-sans-sc.woff2')

async function collectSourceHan(directory, characters) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) {
      if (entry.name !== 'assets' && entry.name !== 'static') await collectSourceHan(path, characters)
    } else if (/\.(vue|ts|scss|json)$/.test(entry.name)) {
      for (const character of (await readFile(path, 'utf8')).match(/\p{Script=Han}/gu) || []) characters.add(character)
    }
  }
}

if (process.argv[2]) {
  const characters = new Set(await readFile(resolve(root, 'src/assets/fonts/common-han.txt'), 'utf8'))
  for (let code = 32; code <= 126; code++) characters.add(String.fromCharCode(code))
  for (const character of '，。！？：；（）【】《》、·—…％℃㎡³¥￥✓×→←↑↓‐－　“”‘’•①②③') characters.add(character)
  await collectSourceHan(resolve(root, 'src'), characters)
  const source = await readFile(resolve(process.argv[2]))
  const subset = await subsetFont(source, [...characters].join(''), {
    targetFormat: 'woff2',
    variationAxes: { wght: { min: 400, max: 700 } },
  })
  await writeFile(fontPath, subset)
  console.log(`Subset ${characters.size} UI characters`)
}

const font = await readFile(fontPath)
const css = `// Generated by pnpm font:css from the bundled Noto Sans SC subset. See src/static/fonts/NotoSansSC-OFL.txt.
@font-face {
  font-family: 'Note Sans SC';
  src: url('data:font/woff2;base64,${font.toString('base64')}') format('woff2');
  font-style: normal;
  font-weight: 400 700;
  font-display: swap;
}
`
await writeFile(resolve(root, 'src/styles/font.scss'), css)
console.log(`Embedded ${font.byteLength} byte UI font`)
